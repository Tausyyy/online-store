
CREATE ROLE lab4_admin
    LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE;

CREATE ROLE lab4_app
    LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE;

CREATE ROLE lab4_analyst
    LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE;

GRANT CONNECT ON DATABASE online_store_lab4
    TO lab4_admin, lab4_app, lab4_analyst;

GRANT USAGE ON SCHEMA public
    TO lab4_admin, lab4_app, lab4_analyst;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public
    TO lab4_admin;

GRANT SELECT, INSERT, UPDATE, DELETE
    ON ALL TABLES IN SCHEMA public
    TO lab4_app;

GRANT SELECT ON ALL TABLES IN SCHEMA public
    TO lab4_analyst;

GRANT USAGE, SELECT, UPDATE
    ON ALL SEQUENCES IN SCHEMA public
    TO lab4_admin, lab4_app;

GRANT SELECT ON ALL SEQUENCES IN SCHEMA public
    TO lab4_analyst;
